#!/usr/bin/env node
/* Inline the stylesheet and every script into one portable HTML file, so the
   builder can be opened from anywhere without its sibling folders. */
'use strict';

const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const out = path.join(root, 'factory-layout-builder.html');

const read = (rel) => fs.readFileSync(path.join(root, rel), 'utf8');

/* A literal </script> inside JS or CSS would end the tag early. */
const guard = (code) => code.replace(/<\/(script|style)/gi, '<\\/$1');

let html = read('index.html');

html = html.replace(
  /[ \t]*<link rel="stylesheet" href="([^"]+)">/,
  (_, href) => '<style>\n' + guard(read(href)) + '</style>'
);

html = html.replace(
  /[ \t]*<script src="([^"]+)"><\/script>\n?/g,
  (_, src) => '<script>\n' + guard(read(src)) + '</script>\n'
);

if (/<link rel="stylesheet"|<script src=/.test(html)) {
  console.error('Some assets were not inlined — check the paths in index.html');
  process.exit(1);
}

html = html.replace(
  '<title>Factory Layout Builder</title>',
  '<title>Factory Layout Builder</title>\n<!-- Standalone build: generated by tools/build-standalone.js. Edit the sources, not this file. -->'
);

fs.writeFileSync(out, html);
console.log('wrote ' + path.relative(root, out) + ' (' + Math.round(html.length / 1024) + ' KB)');
